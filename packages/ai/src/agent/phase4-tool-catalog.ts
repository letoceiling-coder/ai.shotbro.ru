export const PHASE4_TOOLS: Phase4ToolDefinition[] = [
  ...PHASE3_TOOLS.map((t) => ({
    ...t,
    implementationStatus:
      t.id.startsWith("generate.") || t.id === "compose_video"
        ? ("ADAPTER_PENDING" as const)
        : t.id === "request_approval"
          ? ("ORCHESTRATOR_DELEGATE" as const)
          : ("HANDLER" as const),
    inputSchemaVersion: 1,
    timeoutMs: t.sideEffect === "LOCAL_MEDIA_PROCESSING" ? 120_000 : 30_000,
  })),
  ...EXTRA,
];

export function getPhase4Tool(id: string): Phase4ToolDefinition | undefined {
  return PHASE4_TOOLS.find((t) => t.id === id);
}
